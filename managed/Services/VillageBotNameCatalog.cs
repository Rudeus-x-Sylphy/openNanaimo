    public static string Create(int gender, ISet<string> reservedNames)
    {
        var givenNames = gender == 1 ? MaleGivenNames : FemaleGivenNames;
        for (var attempt = 0; attempt < 100; attempt++)
        {
            var name = FamilyNames[Random.Shared.Next(FamilyNames.Length)]
                       + givenNames[Random.Shared.Next(givenNames.Length)];
            if (reservedNames.Add(name))
                return name;
        }

        // The fallback remains within the client's 16-byte GBK name field.
        for (var suffix = 1; ; suffix++)
        {
            var name = $"飞行员{suffix:00}";
            if (reservedNames.Add(name))
                return name;
        }
    }
